        assert not await page.get_by_role('button', name='Save & Proceed').is_enabled()
        await page.unroute('**/applications/*', fail_draft)
        await dialog.get_by_role('button', name='Retry', exact=True).click()
        await page.get_by_label('Loan Purpose').wait_for()
        await expect(page.get_by_label('Loan Purpose')).to_have_value('Borrower supplied renovation purpose')
        await dialog.get_by_role('button', name='Documents', exact=False).click()
        await page.get_by_text('identity.pdf', exact=False).first.wait_for(timeout=15000)
        await page.locator('[data-field="consent"]').check()
        await page.get_by_role('button', name='Submit Application to CredVidhi').dblclick()
