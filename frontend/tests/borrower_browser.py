        await page.get_by_label('Requested Loan Amount').fill('50000')
        await page.get_by_role('button', name='Save & Proceed').click()
        assert await page.get_by_label('Loan Product').is_visible()
        await page.get_by_label('Loan Tenure').fill('24')
        await page.get_by_label('Loan Purpose').fill('Borrower supplied renovation purpose')
        await page.get_by_role('button', name='Save & Proceed').click()
